CREATE TABLE personnel (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  code VARCHAR(64) NOT NULL,
  name VARCHAR(64) NOT NULL,
  personnel_group VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  version INT NOT NULL DEFAULT 0,
  created_by BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by BIGINT UNSIGNED NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0,
  deleted_by BIGINT UNSIGNED NULL,
  deleted_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_personnel_code (code),
  KEY idx_personnel_group_status (personnel_group,status,is_deleted,id),
  CONSTRAINT chk_personnel_group CHECK (personnel_group IN ('production','quality')),
  CONSTRAINT chk_personnel_status CHECK (status IN ('active','inactive')),
  CONSTRAINT chk_personnel_version CHECK (version>=0),
  CONSTRAINT chk_personnel_deleted CHECK ((is_deleted=0 AND deleted_by IS NULL AND deleted_at IS NULL) OR (is_deleted=1 AND deleted_by IS NOT NULL AND deleted_at IS NOT NULL)),
  CONSTRAINT fk_personnel_created_by FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT fk_personnel_updated_by FOREIGN KEY (updated_by) REFERENCES users(id),
  CONSTRAINT fk_personnel_deleted_by FOREIGN KEY (deleted_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
