CREATE TABLE item_batch (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  item_id BIGINT UNSIGNED NOT NULL,
  item_code_snapshot VARCHAR(100) NOT NULL,
  product_name_snapshot VARCHAR(200) NOT NULL,
  unit_snapshot VARCHAR(20) NOT NULL,
  batch_code VARCHAR(100) NOT NULL,
  source_type VARCHAR(30) NOT NULL,
  provider VARCHAR(100) NULL,
  source_work_order_id BIGINT UNSIGNED NULL,
  source_production_batch_id BIGINT UNSIGNED NULL,
  production_date DATE NULL,
  batch_status VARCHAR(20) NOT NULL DEFAULT 'available',
  remark TEXT NULL,
  version INT NOT NULL DEFAULT 0,
  created_by BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by BIGINT UNSIGNED NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_item_batch_item_code (item_id, batch_code),
  UNIQUE KEY uk_item_batch_id_item (id, item_id),
  KEY idx_item_batch_item_status (item_id, batch_status),
  CONSTRAINT chk_item_batch_source_type CHECK (source_type IN ('self_made','purchased','outsourced','return_inbound','stock_check_generated','other')),
  CONSTRAINT chk_item_batch_status CHECK (batch_status IN ('available','frozen','disabled')),
  CONSTRAINT chk_item_batch_version CHECK (version >= 0),
  CONSTRAINT fk_item_batch_item FOREIGN KEY (item_id) REFERENCES products(id),
  CONSTRAINT fk_item_batch_source_work_order FOREIGN KEY (source_work_order_id) REFERENCES work_orders(id),
  CONSTRAINT fk_item_batch_source_production FOREIGN KEY (source_production_batch_id, source_work_order_id) REFERENCES production_batches(id, work_order_id),
  CONSTRAINT fk_item_batch_created_by FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT fk_item_batch_updated_by FOREIGN KEY (updated_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE production_item_allocation (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  demand_id BIGINT UNSIGNED NOT NULL,
  production_batch_id BIGINT UNSIGNED NOT NULL,
  item_id BIGINT UNSIGNED NOT NULL,
  batch_id BIGINT UNSIGNED NOT NULL,
  assigned_number DECIMAL(12,4) NOT NULL,
  unit_snapshot VARCHAR(20) NOT NULL,
  allocation_status VARCHAR(30) NOT NULL DEFAULT 'active',
  version INT NOT NULL DEFAULT 0,
  remark TEXT NULL,
  created_by BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by BIGINT UNSIGNED NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_production_item_allocation_id_demand (id, demand_id),
  UNIQUE KEY uk_production_item_allocation_id_batch (id, production_batch_id),
  UNIQUE KEY uk_production_item_allocation_id_item (id, item_id),
  UNIQUE KEY uk_production_item_allocation_reference (id, demand_id, production_batch_id, item_id, batch_id),
  KEY idx_production_item_allocation_batch_status (production_batch_id, allocation_status),
  KEY idx_production_item_allocation_stock_batch (batch_id, allocation_status),
  CONSTRAINT chk_production_item_allocation_quantity CHECK (assigned_number > 0),
  CONSTRAINT chk_production_item_allocation_status CHECK (allocation_status IN ('active','released','cancelled','frozen','abnormal')),
  CONSTRAINT chk_production_item_allocation_version CHECK (version >= 0),
  CONSTRAINT fk_production_item_allocation_demand_item FOREIGN KEY (demand_id, item_id) REFERENCES production_item_demand(id, item_id),
  CONSTRAINT fk_production_item_allocation_demand_batch FOREIGN KEY (demand_id, production_batch_id) REFERENCES production_item_demand(id, production_batch_id),
  CONSTRAINT fk_production_item_allocation_stock_batch FOREIGN KEY (batch_id, item_id) REFERENCES item_batch(id, item_id),
  CONSTRAINT fk_production_item_allocation_created_by FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT fk_production_item_allocation_updated_by FOREIGN KEY (updated_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

