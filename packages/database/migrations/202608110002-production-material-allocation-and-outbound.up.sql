CREATE TABLE inventory_transaction (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  item_id BIGINT UNSIGNED NOT NULL,
  batch_id BIGINT UNSIGNED NOT NULL,
  transaction_type VARCHAR(30) NOT NULL,
  quantity DECIMAL(12,4) NOT NULL,
  unit_snapshot VARCHAR(20) NOT NULL,
  stock_status VARCHAR(20) NOT NULL DEFAULT 'available',
  reference_type VARCHAR(50) NOT NULL,
  reference_detail_id BIGINT UNSIGNED NOT NULL,
  idempotency_key VARCHAR(150) NOT NULL,
  transaction_group_key VARCHAR(150) NULL,
  reversal_of_transaction_id BIGINT UNSIGNED NULL,
  remark TEXT NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_inventory_transaction_idempotency (idempotency_key),
  UNIQUE KEY uk_inventory_transaction_reversal (reversal_of_transaction_id),
  KEY idx_inventory_transaction_group (transaction_group_key),
  KEY idx_inventory_transaction_stock (item_id, batch_id, stock_status, created_at),
  KEY idx_inventory_transaction_reference (reference_type, reference_detail_id),
  CONSTRAINT chk_inventory_transaction_quantity CHECK (quantity <> 0),
  CONSTRAINT chk_inventory_transaction_type CHECK (transaction_type IN ('purchase_inbound','production_inbound','outsourced_inbound','production_material_outbound','sales_outbound','material_return_inbound','scrap_outbound','stock_check_adjustment','status_transfer_in','status_transfer_out')),
  CONSTRAINT chk_inventory_transaction_stock_status CHECK (stock_status IN ('available','pending_inspection','frozen','defective')),
  CONSTRAINT fk_inventory_transaction_item FOREIGN KEY (item_id) REFERENCES products(id),
  CONSTRAINT fk_inventory_transaction_batch_item FOREIGN KEY (batch_id, item_id) REFERENCES item_batch(id, item_id),
  CONSTRAINT fk_inventory_transaction_reversal FOREIGN KEY (reversal_of_transaction_id) REFERENCES inventory_transaction(id),
  CONSTRAINT fk_inventory_transaction_created_by FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

