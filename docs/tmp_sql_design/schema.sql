CREATE TABLE inventory_transaction (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  item_id BIGINT UNSIGNED NULL,
  material_variant_id BIGINT UNSIGNED NULL,
  product_id BIGINT UNSIGNED NULL,
  batch_id BIGINT UNSIGNED NOT NULL,
  transaction_type VARCHAR(30) NOT NULL,
  quantity INT NOT NULL,
  unit_snapshot VARCHAR(20) NOT NULL,
  stock_status VARCHAR(20) NOT NULL DEFAULT 'available',
  reference_type VARCHAR(50) NOT NULL,
  reference_detail_id BIGINT UNSIGNED NOT NULL,
  idempotency_key VARCHAR(150) NOT NULL,
  transaction_group_key VARCHAR(150) NULL,
  reversal_of_transaction_id BIGINT UNSIGNED NULL,
  remark TEXT NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  inbound_detail_ref BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN reference_type='inbound_detail' THEN reference_detail_id ELSE NULL END) STORED,
  outbound_detail_ref BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN reference_type='outbound_detail' THEN reference_detail_id ELSE NULL END) STORED,
  stock_check_detail_ref BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN reference_type='stock_check_detail' THEN reference_detail_id ELSE NULL END) STORED,
  original_posting_key VARCHAR(100) GENERATED ALWAYS AS (CASE WHEN reversal_of_transaction_id IS NULL AND reference_type IN ('inbound_detail','outbound_detail','stock_check_detail') THEN CONCAT(reference_type,':',reference_detail_id) ELSE NULL END) STORED,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

